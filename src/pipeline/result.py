"""Serializable analysis result models."""

from __future__ import annotations

from dataclasses import asdict, dataclass
from typing import Any


@dataclass(frozen=True)
class MorphologicalFeatures:
    """Morphological descriptors extracted from the nucleus mask."""

    nucleus_area_px: int
    nucleus_perimeter_px: float
    nucleus_solidity: float
    nucleus_eccentricity: float
    nucleus_extent: float
    nucleus_bbox_width_px: int
    nucleus_bbox_height_px: int
    nucleus_segments: int


@dataclass(frozen=True)
class ClassificationResult:
    """Rule-based neutrophil segmentation classification."""

    label: str
    confidence: float
    reason: str


@dataclass(frozen=True)
class AnalysisArtifacts:
    """Paths to files generated by the pipeline."""

    original_image: str
    mask_image: str
    overlay_image: str
    report_json: str
    report_markdown: str
    log_file: str


@dataclass(frozen=True)
class AnalysisResult:
    """Complete API-friendly result for one analyzed image."""

    analysis_id: str
    status: str
    input_filename: str
    image_width_px: int
    image_height_px: int
    features: MorphologicalFeatures
    classification: ClassificationResult
    artifacts: AnalysisArtifacts

    def to_dict(self) -> dict[str, Any]:
        """Convert nested dataclasses to plain dictionaries."""

        return asdict(self)

